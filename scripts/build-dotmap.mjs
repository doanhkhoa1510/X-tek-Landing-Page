// Generates src/scripts/dotmap-data.ts from world-atlas land-110m (Natural Earth, public domain).
// Usage: node scripts/build-dotmap.mjs [path-to-land-110m.json]
import fs from "node:fs";
const topo = JSON.parse(fs.readFileSync(process.argv[2] ?? ".impeccable/land-110m.json", "utf8"));
const { scale: [sx, sy], translate: [tx, ty] } = topo.transform;
const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => [(x += dx) * sx + tx, (y += dy) * sy + ty]);
});
const ringOf = (ids) => ids.flatMap((id, k) => {
  const a = id < 0 ? arcs[~id].slice().reverse() : arcs[id];
  return k ? a.slice(1) : a;
});
const rings = [];
for (const g of topo.objects.land.geometries) {
  const polys = g.type === "Polygon" ? [g.arcs] : g.arcs;
  for (const p of polys) for (const r of p) rings.push(ringOf(r));
}
const inside = (lon, lat) => {
  let c = false;
  for (const r of rings) for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [xi, yi] = r[i], [xj, yj] = r[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
const STEP = 2, LAT0 = 78, LAT1 = -58, LON0 = -180;
const cols = 360 / STEP, rows = (LAT0 - LAT1) / STEP;
const out = [];
let count = 0;
for (let r = 0; r < rows; r++) {
  let bits = "";
  for (let c = 0; c < cols; c++) {
    const on = inside(LON0 + (c + 0.5) * STEP, LAT0 - (r + 0.5) * STEP);
    bits += on ? "1" : "0"; count += on;
  }
  out.push(BigInt("0b" + bits).toString(36));
}
fs.writeFileSync("src/scripts/dotmap-data.ts",
`// Generated by scripts/build-dotmap.mjs from world-atlas land-110m (Natural Earth, public domain). Do not edit.
export const MAP = { step: ${STEP}, lat0: ${LAT0}, lon0: ${LON0}, cols: ${cols}, rows: ${rows} } as const;
export const LAND: readonly string[] = ${JSON.stringify(out)};
`);
console.log({ cols, rows, dots: count });
