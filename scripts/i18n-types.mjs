/* Writes src/i18n/i18next.d.ts from the English namespace files, so t() accepts only keys that exist.
   Run after adding or removing a namespace: npm run i18n:types */
import { readdirSync, writeFileSync } from "node:fs";

const dir = new URL("../src/i18n/locales/en/", import.meta.url);
const names = readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort();
writeFileSync(
  new URL("../src/i18n/i18next.d.ts", import.meta.url),
  `/* Generated by scripts/i18n-types.mjs (npm run i18n:types): typed keys, per namespace, from the English files. */
import "i18next";
${names.map((n) => `import type ${n} from "./locales/en/${n}.json";`).join("\n")}

declare module "i18next" {
  interface CustomTypeOptions {
    defaultNS: "common";
    resources: {
${names.map((n) => `      ${n}: typeof ${n};`).join("\n")}
    };
  }
}
`,
);
console.log(`i18next.d.ts: ${names.length} namespaces`);
